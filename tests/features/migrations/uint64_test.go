package migrations

import (
	"math"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/skudra-go/ant"
)

// CounterV1 has the columns ant made for a uint64 before it was numeric(20,0):
// bigint, which these int64 fields make too.
type CounterV1 struct {
	ID      int64
	Hash    int64
	Tallies []TallyV1
}

func (CounterV1) Configure(b *ant.ModelBuilder[CounterV1]) {
	b.Table("counters")
	b.HasMany(&CounterV1s.Tallies).ForeignKey(&TallyV1s.CounterID)
}

// TallyV1 refers to a CounterV1.
type TallyV1 struct {
	ID        int64
	CounterID int64
}

func (TallyV1) Configure(b *ant.ModelBuilder[TallyV1]) { b.Table("tallies") }

var (
	CounterV1s = ant.Fields[CounterV1]()
	TallyV1s   = ant.Fields[TallyV1]()
)

// CounterV1DB holds CounterV1.
type CounterV1DB struct {
	ant.Context
	Counters ant.Table[CounterV1]
	Tallies  ant.Table[TallyV1]
}

// Counter is CounterV1 with the uint64 fields it stood for. Its key is one the
// database generates.
type Counter struct {
	ID      uint64
	Hash    uint64
	Tallies []Tally
}

// Tally refers to a Counter by its uint64 key.
type Tally struct {
	ID        int64
	CounterID uint64
}

// CounterDB holds Counter.
type CounterDB struct {
	ant.Context
	Counters ant.Table[Counter]
	Tallies  ant.Table[Tally]
}

// A uint64 column is numeric(20,0), which holds every value one can take, so
// the next diff of a table ant made converts it. An identity can only be an
// integer, and counts up from 1, so a key the database generates stays bigint,
// and so does a uint64 foreign key to it, which PostgreSQL would refuse to point
// at a bigint from a numeric column (#206).
func TestUint64Columns(t *testing.T) {
	each(t, func(t *testing.T, p *project) {
		must[CounterV1DB](p, "diff", "start")
		must[CounterV1DB](p, "up")

		out := must[CounterDB](p, "diff", "wide")
		require.Contains(t, out, "change column counters.hash: type bigint to numeric(20,0)")
		require.NotContains(t, out, "counters.id")
		require.NotContains(t, out, "tallies.counter_id")

		must[CounterDB](p, "up")
		require.Contains(t, must[CounterDB](p, "drift"), "No drift")

		db := open[CounterDB](p)

		counter := &Counter{
			Hash:    math.MaxUint64,
			Tallies: []Tally{{}},
		}
		require.NoError(t, ant.Session(db).Counters.Insert(t.Context(), counter))

		got, err := db.Counters.Include(&Counters.Tallies).Find(t.Context(), counter.ID)
		require.NoError(t, err)
		require.Equal(t, uint64(math.MaxUint64), got.Hash)
		require.Len(t, got.Tallies, 1)
	})
}

// Counters is Counter's probe.
var Counters = ant.Fields[Counter]()

// A new model with a generated uint64 key opens a table PostgreSQL accepts: an
// identity of numeric(20,0) is refused.
func TestUint64GeneratedKey(t *testing.T) {
	each(t, func(t *testing.T, p *project) {
		must[CounterDB](p, "diff", "start")

		file := p.read("versions/0001_start.up.sql")
		require.Contains(t, file, `"id" bigint GENERATED BY DEFAULT AS IDENTITY`)
		require.Contains(t, file, `"hash" numeric(20,0) NOT NULL`)
		require.Contains(t, file, `"counter_id" bigint NOT NULL`)

		must[CounterDB](p, "up")
		require.Contains(t, must[CounterDB](p, "drift"), "No drift")
	})
}

// Ledger has a uint64 key the application gives, such as a hash, so it is
// numeric(20,0).
type Ledger struct {
	ID      uint64
	Entries []Entry
}

func (Ledger) Configure(b *ant.ModelBuilder[Ledger]) {
	b.Key(&Ledgers.ID).NotGenerated()
}

// Entry refers to a Ledger through an int64.
type Entry struct {
	ID       int64
	LedgerID int64
}

var Ledgers = ant.Fields[Ledger]()

// LedgerDB holds Ledger.
type LedgerDB struct {
	ant.Context
	Ledgers ant.Table[Ledger]
	Entries ant.Table[Entry]
}

// A foreign key to a uint64 key takes the key's type, whatever integer refers
// to it, as PostgreSQL refuses one from bigint to numeric.
func TestUint64ForeignKeyFollowsItsKey(t *testing.T) {
	each(t, func(t *testing.T, p *project) {
		must[LedgerDB](p, "diff", "start")

		file := p.read("versions/0001_start.up.sql")
		require.Contains(t, file, `"id" numeric(20,0) NOT NULL`)
		require.Contains(t, file, `"ledger_id" numeric(20,0) NOT NULL`)

		must[LedgerDB](p, "up")
		require.Contains(t, must[LedgerDB](p, "drift"), "No drift")
	})
}
