// Package concurrency runs ant the way a server does, from many goroutines at
// once, on every database: one shared context, a session per worker, and
// transactions that contend for the same rows. Run it under the race detector,
// which is where most of its failures would show.
package concurrency

import (
	"context"
	"database/sql"
	"fmt"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/skudra-go/ant"
	"github.com/skudra-go/ant/internal/testdb"
)

// Account is a row many workers change at once.
type Account struct {
	ID       int64
	Owner    string
	Balance  int64
	Version  int64 `ant:"version"`
	Payments []Payment
	counted  int // set by a hook in TestHookGoroutinesShareTheClaim
}

func (Account) Configure(b *ant.ModelBuilder[Account]) { b.Table("cc_accounts") }

// Payment belongs to an account.
type Payment struct {
	ID        int64
	AccountID int64
	Amount    int64
	Note      string
	Account   *Account
}

func (Payment) Configure(b *ant.ModelBuilder[Payment]) { b.Table("cc_payments") }

// Counter has a key the application chooses, so workers can race to create it.
type Counter struct {
	Name string
	Hits int64
}

func (Counter) Configure(b *ant.ModelBuilder[Counter]) {
	b.Table("cc_counters")
	b.Key(&Counters.Name)
}

// Ticket has hooks, which run on whichever goroutine writes or loads it.
type Ticket struct {
	ID    int64
	Title string
	Loads int `ant:"-"`
}

func (Ticket) Configure(b *ant.ModelBuilder[Ticket]) { b.Table("cc_tickets") }

// BankDB is the context the workers share or take sessions of.
type BankDB struct {
	ant.Context
	Accounts ant.Table[Account]
	Payments ant.Table[Payment]
	Counters ant.Table[Counter]
	Tickets  ant.Table[Ticket]
}

var (
	Accounts = ant.Fields[Account]()
	Payments = ant.Fields[Payment]()
	Counters = ant.Fields[Counter]()
)

// ddl holds the column types that differ between databases.
type ddl struct{ id, text string }

var ddls = map[string]ddl{
	"postgres":  {"BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "VARCHAR(255)"},
	"mysql":     {"BIGINT AUTO_INCREMENT PRIMARY KEY", "VARCHAR(255)"},
	"mariadb":   {"BIGINT AUTO_INCREMENT PRIMARY KEY", "VARCHAR(255)"},
	"sqlite":    {"INTEGER PRIMARY KEY AUTOINCREMENT", "VARCHAR(255)"},
	"sqlserver": {"BIGINT IDENTITY PRIMARY KEY", "NVARCHAR(255)"},
}

// each runs fn on every database in ANT_TEST_DATABASES. The tables are this
// package's own, so the shared fixture tables, which another package may be
// using at the time, are left alone.
func each(t *testing.T, fn func(t *testing.T, target testdb.Target)) {
	t.Helper()

	targets := testdb.Targets()
	if len(targets) == 0 {
		t.Skip("no database in ANT_TEST_DATABASES")
	}

	for _, target := range targets {
		t.Run(target.Name, func(t *testing.T) {
			target.Connect(t)
			create(t, target)

			if target.Name == "sqlite" {
				// SQLite has one writer at a time. Waiting for the lock, and
				// taking it when a transaction begins, is what lets several
				// connections write; without them a second writer fails at once.
				// WAL lets readers go on beside the writer, and stays with the
				// file, so it is set once rather than by every new connection,
				// which would need the write lock to set it.
				_, err := target.DB.ExecContext(t.Context(), "PRAGMA journal_mode=WAL")
				require.NoError(t, err)

				target.DSN += "&_pragma=busy_timeout(20000)&_txlock=immediate"
			}

			fn(t, target)
		})
	}
}

func create(t *testing.T, target testdb.Target) {
	t.Helper()

	d := ddls[target.Name]

	drop := func() {
		for _, table := range []string{"cc_payments", "cc_counters", "cc_accounts", "cc_tickets"} {
			_, _ = target.DB.ExecContext(context.Background(), "DROP TABLE "+table)
		}
	}

	drop()
	t.Cleanup(drop)

	for _, stmt := range []string{
		fmt.Sprintf(
			`CREATE TABLE cc_accounts (
			id %[1]s,
			owner %[2]s NOT NULL UNIQUE,
			balance BIGINT NOT NULL,
			version BIGINT NOT NULL)`,
			d.id,
			d.text,
		),
		fmt.Sprintf(
			`CREATE TABLE cc_payments (
			id %[1]s,
			account_id BIGINT NOT NULL REFERENCES cc_accounts (id) ON DELETE CASCADE,
			amount BIGINT NOT NULL,
			note %[2]s NOT NULL)`,
			d.id,
			d.text,
		),
		fmt.Sprintf(
			`CREATE TABLE cc_counters (
			name %[1]s NOT NULL PRIMARY KEY,
			hits BIGINT NOT NULL)`,
			d.text,
		),
		fmt.Sprintf(
			`CREATE TABLE cc_tickets (
			id %[1]s,
			title %[2]s NOT NULL)`,
			d.id,
			d.text,
		),
	} {
		_, err := target.DB.ExecContext(t.Context(), stmt)
		require.NoError(t, err)
	}
}

// open opens a BankDB on target and closes it when the test ends, failing the
// test if any connection is still in use by then.
func open(t *testing.T, target testdb.Target, options ...ant.Option) *BankDB {
	t.Helper()

	db, err := ant.Open[BankDB](t.Context(), target.Dialect, target.DSN, options...)
	require.NoError(t, err)

	t.Cleanup(func() {
		if inUse := db.DB().Stats().InUse; inUse != 0 {
			t.Errorf("%d connections still in use", inUse)
		}

		db.Close()
	})

	return db
}

// shared opens the context a server shares between its requests: tracking off.
func shared(t *testing.T, target testdb.Target, options ...ant.Option) *BankDB {
	t.Helper()

	return open(t, target, append([]ant.Option{ant.WithTracking(false)}, options...)...)
}

// seedAccounts inserts n accounts, owner-0 to owner-(n-1), each with balance.
func seedAccounts(t *testing.T, db *BankDB, n int, balance int64) []*Account {
	t.Helper()

	accounts := make([]*Account, n)

	for i := range accounts {
		accounts[i] = &Account{Owner: fmt.Sprintf("owner-%d", i), Balance: balance}
	}

	_, err := db.Accounts.InsertMany(t.Context(), accounts)
	require.NoError(t, err)

	if accounts[0].ID == 0 {
		// Bulk inserts on some databases do not return keys.
		stored, err := db.Accounts.NoTracking().OrderBy(&Accounts.ID).All(t.Context())
		require.NoError(t, err)

		accounts = stored
	}

	return accounts
}

// total returns the sum of all balances, read straight from the database.
func total(t *testing.T, db *BankDB) int64 {
	t.Helper()

	var sum sql.NullInt64

	require.NoError(t, db.DB().QueryRowContext(
		t.Context(),
		"SELECT SUM(balance) FROM cc_accounts",
	).Scan(&sum))

	return sum.Int64
}

// workers runs n goroutines, each given its number, and returns their errors.
func workers(n int, work func(i int) error) []error {
	errs := make([]error, n)
	done := make(chan struct{})

	for i := range n {
		go func() {
			defer func() { done <- struct{}{} }()

			errs[i] = work(i)
		}()
	}

	for range n {
		<-done
	}

	return errs
}

// noErrors fails the test with every error a worker returned.
func noErrors(t *testing.T, errs []error) {
	t.Helper()

	for i, err := range errs {
		require.NoError(t, err, "worker %d", i)
	}
}
