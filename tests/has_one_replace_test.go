// Holder has one Pass, whose key is required, and one Locker, whose key is
// nullable. Each key is unique, as a one-to-one relation's usually is.
type Holder struct {
	ID     int64
	Name   string
	Pass   *Pass
	Locker *Locker
}

// Pass is deleted when its holder lets go of it.
type Pass struct {
	ID       int64
	HolderID int64
	Code     string
}

// Locker is kept, with no holder, when its holder lets go of it.
type Locker struct {
	ID       int64
	HolderID *int64
	Number   int
}

// HolderDB holds holders and what they have one of.
type HolderDB struct {
	ant.Context
	Holders ant.Table[Holder]
	Passes  ant.Table[Pass]
	Lockers ant.Table[Locker]
}

var (
	Holders = ant.Fields[Holder]()
	Passes  = ant.Fields[Pass]()
	Lockers = ant.Fields[Locker]()
)

func openHolders(t *testing.T, target testdb.Target) *HolderDB {
	t.Helper()
	ctx := t.Context()

	key := map[string]string{
		"postgres":  "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
		"mysql":     "BIGINT AUTO_INCREMENT PRIMARY KEY",
		"mariadb":   "BIGINT AUTO_INCREMENT PRIMARY KEY",
		"sqlite":    "INTEGER PRIMARY KEY AUTOINCREMENT",
		"sqlserver": "BIGINT IDENTITY PRIMARY KEY",
	}[target.Name]

	// SQL Server's unique index counts NULL as a value, unless it is filtered.
	someone := ""

	if target.Name == "sqlserver" {
		someone = " WHERE holder_id IS NOT NULL"
	}

	for _, ddl := range []string{
		`CREATE TABLE holders (id ` + key + `, name VARCHAR(40) NOT NULL)`,
		`CREATE TABLE passes (id ` + key + `, holder_id BIGINT NOT NULL, code VARCHAR(40) NOT NULL)`,
		`CREATE UNIQUE INDEX passes_holder ON passes (holder_id)`,
		`CREATE TABLE lockers (id ` + key + `, holder_id BIGINT NULL, number INT NOT NULL)`,
		`CREATE UNIQUE INDEX lockers_holder ON lockers (holder_id)` + someone,
	} {
		_, err := target.DB.ExecContext(ctx, ddl)
		require.NoError(t, err)
	}

	t.Cleanup(func() {
		for _, table := range []string{"lockers", "passes", "holders"} {
			_, _ = target.DB.ExecContext(context.Background(), "DROP TABLE "+table)
		}
	})

	db, err := ant.Open[HolderDB](ctx, target.Dialect, target.DSN)
	require.NoError(t, err)
	t.Cleanup(func() { db.Close() })

	return db
}

// A has-one pointer is the truth about its relation, as a slice is: replacing
// or clearing a loaded one deletes the row it held, or clears that row's key
// when the key is nullable. A row that moved to another holder stays (#292).
func TestConformanceHasOneReplacedOrCleared(t *testing.T) {
	testdb.ForEach(t, func(t *testing.T, target testdb.Target) {
		root := openHolders(t, target)
		ctx := t.Context()

		// seed inserts a holder with a pass and a locker, and returns its key.
		seed := func(t *testing.T, name string) int64 {
			t.Helper()

			s := ant.Session(root)

			h := &Holder{
				Name:   name,
				Pass:   &Pass{Code: name + "-1"},
				Locker: &Locker{Number: 1},
			}
			require.NoError(t, ant.Add(ctx, s, h))
			require.NoError(t, s.SaveChanges(ctx))

			return h.ID
		}

		load := func(t *testing.T, s *HolderDB, id int64) *Holder {
			t.Helper()

			h, err := s.Holders.IncludeOne(&Holders.Pass).IncludeOne(&Holders.Locker).Find(ctx, id)
			require.NoError(t, err)
			require.NotNil(t, h.Pass)
			require.NotNil(t, h.Locker)

			return h
		}

		passes := func(t *testing.T, id int64) []string {
			t.Helper()

			got, err := root.Passes.Where(ant.Eq(&Passes.HolderID, id)).OrderBy(&Passes.ID).All(ctx)
			require.NoError(t, err)

			var codes []string

			for _, p := range got {
				codes = append(codes, p.Code)
			}

			return codes
		}

		lockers := func(t *testing.T, id int64) []int {
			t.Helper()

			got, err := root.Lockers.Where(ant.Eq(&Lockers.HolderID, &id)).
				OrderBy(&Lockers.ID).
				All(ctx)
			require.NoError(t, err)

			var numbers []int

			for _, l := range got {
				numbers = append(numbers, l.Number)
			}

			return numbers
		}

		unheld := func(t *testing.T) int64 {
			t.Helper()

			n, err := root.Lockers.Where(ant.IsNull(&Lockers.HolderID)).Count(ctx)
			require.NoError(t, err)

			return n
		}

		t.Run("replaced", func(t *testing.T) {
			id := seed(t, "ann")
			before := unheld(t)

			s := ant.Session(root)
			h := load(t, s, id)
			h.Pass = &Pass{Code: "ann-2"}
			h.Locker = &Locker{Number: 2}

			changed, err := s.HasChanges(ctx)
			require.NoError(t, err)
			require.True(t, changed)
			require.NoError(t, s.SaveChanges(ctx))

			require.Equal(t, []string{"ann-2"}, passes(t, id), "the old pass is deleted")
			require.Equal(t, []int{2}, lockers(t, id))
			require.Equal(t, before+1, unheld(t), "the old locker is kept, with no holder")

			again := load(t, ant.Session(root), id)
			require.Equal(t, "ann-2", again.Pass.Code)
			require.Equal(t, 2, again.Locker.Number)
		})

		t.Run("cleared", func(t *testing.T) {
			id := seed(t, "bob")
			before := unheld(t)

			s := ant.Session(root)
			h := load(t, s, id)
			h.Pass = nil
			h.Locker = nil

			changed, err := s.HasChanges(ctx)
			require.NoError(t, err)
			require.True(t, changed)
			require.NoError(t, s.SaveChanges(ctx))

			require.Empty(t, passes(t, id))
			require.Empty(t, lockers(t, id))
			require.Equal(t, before+1, unheld(t))
		})

		t.Run("cleared after the graph was inserted", func(t *testing.T) {
			s := ant.Session(root)

			h := &Holder{
				Name: "cat",
				Pass: &Pass{Code: "cat-1"},
			}
			require.NoError(t, ant.Add(ctx, s, h))
			require.NoError(t, s.SaveChanges(ctx))

			h.Pass = nil

			require.NoError(t, s.SaveChanges(ctx))
			require.Empty(t, passes(t, h.ID))
		})

		t.Run("moved to another holder", func(t *testing.T) {
			from := seed(t, "dan")

			s := ant.Session(root)
			a := load(t, s, from)

			c := &Holder{
				Name:   "fay",
				Pass:   a.Pass,
				Locker: a.Locker,
			}

			a.Pass, a.Locker = nil, nil

			require.NoError(t, ant.Add(ctx, s, c))
			require.NoError(t, s.SaveChanges(ctx))

			require.Empty(t, passes(t, from))
			require.Equal(t, []string{"dan-1"}, passes(t, c.ID), "the pass moved, not deleted")
			require.Equal(t, []int{1}, lockers(t, c.ID))
		})
	})
}

// A has-one relation that picks one row of many, with Latest, is a view of
// them: clearing it leaves the rows alone.
func TestConformanceHasOnePickedIsLeftAlone(t *testing.T) {
	testdb.ForEach(t, func(t *testing.T, target testdb.Target) {
		root := openTickets(t, target)
		ctx := t.Context()

		require.NoError(t, root.Tickets.Insert(ctx, &Ticket{ID: 1}))
		require.NoError(t, root.TicketNotes.Insert(ctx, &TicketNote{ID: 10, TicketID: 1}))

		s := ant.Session(root)
		got, err := s.Tickets.IncludeOne(&Tickets.LastNote).Find(ctx, int64(1))
		require.NoError(t, err)
		require.NotNil(t, got.LastNote)

		got.LastNote = nil

		require.NoError(t, s.SaveChanges(ctx))

		n, err := root.TicketNotes.Count(ctx)
		require.NoError(t, err)
		require.Equal(t, int64(1), n)
	})
}
